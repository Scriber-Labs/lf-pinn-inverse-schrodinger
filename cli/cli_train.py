# cli_train.py
"""
Command-line training runner for Project 2 (``lf-pinn-inverse-schrodinger``).

The purpose of this script is to provide a reproducible command-line interface
around the canonical training primitives in ``src/train.py``. It mirrors the
main workflow in ``notebooks/demo.ipynb``: synthetic harmonic-oscillator data
generation, PINN training, POD diagnostics, saved figures, saved artifacts, and
SQLite run logging.

Generated run artifacts include:
- ``config.json``: training configuration and hyperparameters
- ``history.json``: per-epoch loss history
- ``diagnostics.npz``: learned energies, potential, wavefunctions, and POD data
- ``ground_truth.pt``: analytic reference quantities for comparison
- ``model.pt``: trained model state dictionary
- ``run_id.txt``: unique identifier for the run
- notebook-matching diagnostic PNG figures

Usage examples
--------------
Run with notebook-matching defaults from the project root:

    python -m cli.cli_train

Run with explicit loss weights:

    python -m cli.cli_train \\
        --lambda-data 1.5 \\
        --lambda-physics 0.5 \\
        --lambda-smooth 0.05 \\
        --lambda-ordered 1.0

Write figures to the notebook demo visuals directory:

    python -m cli.cli_train --figures-dir artifacts/demo_visuals

Display figures interactively after saving:

    python -m cli.cli_train --show-figures

Provenance: Initial implementation generated by an LLM and not yet fully reviewed by a human maintainer.
Maintainer: Eigenscribe / Scriber Labs
Date: 02-2026
"""

